"""Hand-drawn multi-frame ASCII sprites.

Colour masks are generated by small rule functions instead of hand-typed
parallel strings, which keeps the art readable and easy to edit: change the
drawing, the colours follow.
"""
from __future__ import annotations

from typing import Callable, Dict, List

from ..canvas import Sprite


def auto_masks(frames: List[str], rule: Callable[[str, int, int, int], str]) -> List[str]:
    out = []
    for f in frames:
        lines = Sprite._lines(f)
        w = max(len(l) for l in lines)
        out.append("\n".join("".join(rule(c, x, y, w) for x, c in enumerate(l))
                             for y, l in enumerate(lines)))
    return out


# ------------------------------------------------------------------ butterfly
BUTTERFLY_FRAMES = [
    r"""
 .-~~-.   .-~~-.
(  ❀   \ /   ❀  )
 \   .  Y  .   /
  >-'  (|)  '-<
 (  ✿  /|\  ✿  )
  '--'  .  '--'
""",
    r"""
   .-~-. .-~-.
   ( ❀ \ / ❀ )
    \ . Y . /
    >-'(|)'-<
    ( ✿/|\✿ )
     '-' '-'
""",
    r"""
       \ /
      (\Y/)
       (|)
      (/|\)
        '

""",
]


def _butterfly_rule(c, x, y, w):
    if c in "❀✿":
        return "p"
    if 7 <= x <= 9 and c in "Y|()/\\'":
        return "b"
    if c == ".":
        return "p"
    return "w"


BUTTERFLY = Sprite(BUTTERFLY_FRAMES, auto_masks(BUTTERFLY_FRAMES, _butterfly_rule))
BUTTERFLY_CYCLE = [0, 1, 2, 1]

SMALL_BUTTERFLY = ["ʚ|ɞ", "\\|/", "(|)", "\\|/"]

# --------------------------------------------------------------------- cherub
CHERUB_FRAMES = [
    r"""
 __                 __
(  `\.    ___    ./`  )
 \  ~ \  (@@@)  / ~  /
  \ ~  \(o . o)/  ~ /
   '.~  ( \_/ )  ~.'
     '-./'---'\.-'
         /   \
        (_/ \_)
""",
    r"""

          ___
  .-~~-. (@@@) .-~~-.
 ( ~ ~ \(o . o)/ ~ ~ )
  '.~ ~.( \_/ ).~ ~.'
     '-./'---'\.-'
         /   \
        (_/ \_)
""",
]


def _cherub_rule(c, x, y, w):
    if c == "@":
        return "h"  # golden curls
    if 8 <= x <= 14 and 2 <= y <= 4 and c not in "~":
        return "s"  # skin
    if 9 <= x <= 14 and y >= 5:
        return "s"
    if c == "~":
        return "f"  # feather detail
    return "w"


CHERUB = Sprite(CHERUB_FRAMES, auto_masks(CHERUB_FRAMES, _cherub_rule))

