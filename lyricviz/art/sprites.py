# -------------------------------------------------------------------- snowman
SNOWMAN_FRAMES = [
    r"""
      ___
     |   |
    _|___|_
     (o o)
 \   ( > )   /
  \ (  •  ) /
   (   •   )
  (    •    )
   '-------'
""",
    r"""
      ___
     |   |
    _|___|_
     (o o)
     ( > )
  --(  •  )--
   (   •   )
  (    •    )
   '-------'
""",
]


def _snowman_rule(c, x, y, w):
    if y <= 2:
        return "h"  # hat
    if c == ">":
        return "c"  # carrot
    if c == "•":
        return "k"  # coal buttons
    if c in "\\/-" and (x <= 3 or x >= 11):
        return "a"  # twig arms
    if c == "o" and y == 3:
        return "k"
    return "s"


SNOWMAN = Sprite(SNOWMAN_FRAMES, auto_masks(SNOWMAN_FRAMES, _snowman_rule))

