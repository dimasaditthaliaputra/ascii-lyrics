HEIGHT = 5
FONT: Dict[str, List[str]] = _RAW


def glyph(ch: str) -> List[str]:
    return FONT.get(ch.upper(), FONT["?"])


def measure(text: str, spacing: int = 1) -> int:
    if not text:
        return 0
    return sum(len(glyph(c)[0]) for c in text) + spacing * (len(text) - 1)


def layout(text: str, spacing: int = 1):
    """Yield (char_index, x_offset, rows) for each glyph."""
    x = 0
    for i, c in enumerate(text):
        g = glyph(c)
        yield i, x, g
        x += len(g[0]) + spacing
